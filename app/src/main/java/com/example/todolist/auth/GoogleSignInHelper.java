package com.example.todolist.auth;

import android.app.Activity;
import android.os.CancellationSignal;
import androidx.annotation.NonNull;
import androidx.annotation.Nullable;
import androidx.annotation.StringRes;
import androidx.core.content.ContextCompat;
import androidx.credentials.Credential;
import androidx.credentials.CredentialManager;
import androidx.credentials.CredentialManagerCallback;
import androidx.credentials.CustomCredential;
import androidx.credentials.GetCredentialRequest;
import androidx.credentials.GetCredentialResponse;
import androidx.credentials.exceptions.GetCredentialCancellationException;
import androidx.credentials.exceptions.GetCredentialException;
import androidx.credentials.exceptions.NoCredentialException;
import com.example.todolist.R;
import com.google.android.libraries.identity.googleid.GetSignInWithGoogleOption;
import com.google.android.libraries.identity.googleid.GoogleIdTokenCredential;
import com.google.firebase.auth.AdditionalUserInfo;
import com.google.firebase.auth.AuthCredential;
import com.google.firebase.auth.FirebaseAuth;
import com.google.firebase.auth.FirebaseUser;
import com.google.firebase.auth.GoogleAuthProvider;

/**
 * "Continue with Google": the system account sheet (Credential Manager) returns a Google ID token, which is
 * exchanged for a Firebase session. The same call serves sign-in and first-time registration; Firebase
 * creates the account on the first use and says so in {@code isNewUser}.
 */
public final class GoogleSignInHelper {

    public interface Callback {
        /**
         * @param isNewUser   true when this sign-in created the account
         * @param displayName the name on the Google account, may be null
         */
        void onSignedIn(@NonNull FirebaseUser user, boolean isNewUser, @Nullable String displayName);

        /** The user closed the account sheet. Nothing to report. */
        void onCancelled();

        void onError(@StringRes int messageRes, @Nullable String detail);
    }

    private GoogleSignInHelper() {
    }

    public static void start(@NonNull Activity activity, @NonNull Callback callback) {
        // Generated by the Google Services plugin once Google sign-in is enabled in Firebase and
        // google-services.json is refreshed. Looked up by name so the app still builds without it.
        int id = activity.getResources().getIdentifier("default_web_client_id", "string", activity.getPackageName());
        if (id == 0) {
            callback.onError(R.string.google_not_configured, null);
            return;
        }
        String webClientId = activity.getString(id);

        GetSignInWithGoogleOption option = new GetSignInWithGoogleOption.Builder(webClientId).build();
        GetCredentialRequest request = new GetCredentialRequest.Builder().addCredentialOption(option).build();
        CredentialManager manager = CredentialManager.create(activity);
        manager.getCredentialAsync(activity, request, new CancellationSignal(),
                ContextCompat.getMainExecutor(activity),
                new CredentialManagerCallback<GetCredentialResponse, GetCredentialException>() {
                    @Override
                    public void onResult(GetCredentialResponse result) {
                        handleCredential(result.getCredential(), callback);
                    }

                    @Override
                    public void onError(@NonNull GetCredentialException e) {
                        if (e instanceof GetCredentialCancellationException) {
                            callback.onCancelled();
                        } else if (e instanceof NoCredentialException) {
                            callback.onError(R.string.google_no_account, e.getMessage());
                        } else {
                            callback.onError(R.string.google_failed, e.getMessage());
                        }
                    }
                });
    }

    private static void handleCredential(Credential credential, Callback callback) {
        String idToken;
        String displayName;
        try {
            if (!(credential instanceof CustomCredential)) {
                callback.onError(R.string.google_failed, null);
                return;
            }
            GoogleIdTokenCredential google = GoogleIdTokenCredential.createFrom(credential.getData());
            idToken = google.getIdToken();
            displayName = google.getDisplayName();
        } catch (Exception e) {
            // Not a Google credential or unreadable data.
            callback.onError(R.string.google_failed, e.getMessage());
            return;
        }

        AuthCredential firebaseCredential = GoogleAuthProvider.getCredential(idToken, null);
        FirebaseAuth.getInstance().signInWithCredential(firebaseCredential).addOnCompleteListener(task -> {
            FirebaseUser user = task.isSuccessful() && task.getResult() != null
                    ? task.getResult().getUser() : null;
            if (user == null) {
                Exception failure = task.getException();
                callback.onError(AuthErrors.messageFor(failure, R.string.google_failed),
                        failure == null ? null : failure.getMessage());
                return;
            }
            AdditionalUserInfo info = task.getResult().getAdditionalUserInfo();
            callback.onSignedIn(user, info != null && info.isNewUser(), displayName);
        });
    }
}
